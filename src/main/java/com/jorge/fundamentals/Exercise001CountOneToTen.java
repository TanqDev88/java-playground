package com.jorge.fundamentals;

public class Exercise001CountOneToTen {
    /*
    Ejercicio 1 - Contar del 1 al 10

        Mostrar todos los números del 1 al 10 usando for.

    Conceptos: bucle for + contador incremental.
     */
    public static void main(String[] args) {

        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }

    }
}
